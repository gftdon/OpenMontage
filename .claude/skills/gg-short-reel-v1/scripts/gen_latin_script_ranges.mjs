// Generates latin_script_ranges.py: every code point matched by /\p{Script=Latin}/u, as inclusive (start, end) ranges.
// This is the single standard for "Latin" shared with AIOS (which uses the same regex). Regenerate with:
//   node .claude/skills/gg-short-reel-v1/scripts/gen_latin_script_ranges.mjs > .claude/skills/gg-short-reel-v1/scripts/latin_script_ranges.py
const re = /\p{Script=Latin}/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const hit = re.test(String.fromCodePoint(cp)); // lone surrogates are not Latin
  if (hit && start < 0) start = cp;
  if (!hit && start >= 0) {
    ranges.push([start, cp - 1]);
    start = -1;
  }
}
if (start >= 0) ranges.push([start, 0x10ffff]);
const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");
const lines = ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`);
process.stdout.write(
  `"""GENERATED FILE - do not edit by hand.
Inclusive (start, end) code point ranges of the JavaScript regex property Script=Latin (the same standard AIOS uses).
Generated by: gen_latin_script_ranges.mjs
Node: ${process.version}   Unicode (process.versions.unicode): ${process.versions.unicode}
Regenerate:  node .claude/skills/gg-short-reel-v1/scripts/gen_latin_script_ranges.mjs > .claude/skills/gg-short-reel-v1/scripts/latin_script_ranges.py
"""
NODE_VERSION = "${process.version}"
UNICODE_VERSION = "${process.versions.unicode}"
LATIN_RANGES = (
${lines.join("\n")}
)
`,
);
