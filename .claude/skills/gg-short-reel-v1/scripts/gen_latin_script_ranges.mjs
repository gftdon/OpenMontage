// Generates latin_script_ranges.py with two tables of inclusive (start, end) code point ranges:
//   LATIN_RANGES            = /\p{Script=Latin}/u                          (kept for reference / parity tests)
//   NON_LATIN_LETTER_RANGES = /\p{L}/u AND NOT /\p{Script=Latin}/u          (the ONLY table overlay.py decides from)
// This is the single standard for "Latin" shared with AIOS (which uses the same regexes). Regenerate with:
//   node .claude/skills/gg-short-reel-v1/scripts/gen_latin_script_ranges.mjs > .claude/skills/gg-short-reel-v1/scripts/latin_script_ranges.py
const latin = /\p{Script=Latin}/u;
const letter = /\p{L}/u;
const rangesOf = (pred) => {
  const ranges = [];
  let start = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const hit = pred(String.fromCodePoint(cp)); // lone surrogates match neither regex
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      ranges.push([start, cp - 1]);
      start = -1;
    }
  }
  if (start >= 0) ranges.push([start, 0x10ffff]);
  return ranges;
};
const latinRanges = rangesOf((s) => latin.test(s));
const nonLatinLetterRanges = rangesOf((s) => letter.test(s) && !latin.test(s));
const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");
const fmt = (ranges) => ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join("\n");
process.stdout.write(
  `"""GENERATED FILE - do not edit by hand.
Inclusive (start, end) code point ranges taken from JavaScript regex properties (the same standard AIOS uses):
  LATIN_RANGES            = Script=Latin
  NON_LATIN_LETTER_RANGES = General_Category=L and not Script=Latin  (overlay.py decides "offending letter" from this table only)
Generated by: gen_latin_script_ranges.mjs
Node: ${process.version}   Unicode (process.versions.unicode): ${process.versions.unicode}
Regenerate:  node .claude/skills/gg-short-reel-v1/scripts/gen_latin_script_ranges.mjs > .claude/skills/gg-short-reel-v1/scripts/latin_script_ranges.py
"""
NODE_VERSION = "${process.version}"
UNICODE_VERSION = "${process.versions.unicode}"
LATIN_RANGES = (
${fmt(latinRanges)}
)
NON_LATIN_LETTER_RANGES = (
${fmt(nonLatinLetterRanges)}
)
`,
);
